-- =====================================================================
--  Эко-сервис: сервис формирования экологической культуры обучающихся
--  Скрипт создания базы данных для PostgreSQL 16
--
--  Порядок импорта:
--    createdb -U postgres -E UTF8 ecoservice
--    psql -U postgres -d ecoservice -f sql/ecoservice.sql
--
--  Скрипт идемпотентен: при повторном запуске таблицы пересоздаются.
-- =====================================================================

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET client_min_messages = warning;

DROP TABLE IF EXISTS feedback, user_badges, event_registrations, enrollments,
  materials, course_sections, eco_entries, events, courses, badges,
  action_types, users CASCADE;

-- =====================================================================
--  СТРУКТУРА ТАБЛИЦ
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Пользователи и роли
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY,
  name          varchar(100) NOT NULL,
  email         varchar(190) NOT NULL,
  password_hash varchar(255) NOT NULL,
  role          varchar(16)  NOT NULL DEFAULT 'student',
  created_at    timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT users_pkey PRIMARY KEY (id),
  CONSTRAINT users_role_check CHECK (role IN ('student', 'teacher', 'admin'))
);
-- email уникален без учёта регистра (в MySQL это обеспечивала collation *_ci)
CREATE UNIQUE INDEX users_email_key ON users (lower(email));

COMMENT ON TABLE  users               IS 'Пользователи сервиса: студенты, преподаватели и администраторы';
COMMENT ON COLUMN users.id            IS 'Идентификатор пользователя';
COMMENT ON COLUMN users.name          IS 'ФИО (отображаемое имя)';
COMMENT ON COLUMN users.email         IS 'Адрес электронной почты (логин), уникален без учёта регистра';
COMMENT ON COLUMN users.password_hash IS 'Хэш пароля (bcrypt, функция password_hash в PHP)';
COMMENT ON COLUMN users.role          IS 'Роль: student — студент, teacher — преподаватель, admin — администратор';
COMMENT ON COLUMN users.created_at    IS 'Дата и время регистрации';

-- ---------------------------------------------------------------------
-- 2. Справочник видов экологических действий
-- ---------------------------------------------------------------------
CREATE TABLE action_types (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  name        varchar(120) NOT NULL,
  unit        varchar(32)  NOT NULL DEFAULT 'шт.',
  description varchar(500),
  is_active   boolean      NOT NULL DEFAULT true,
  CONSTRAINT action_types_pkey PRIMARY KEY (id),
  CONSTRAINT action_types_name_key UNIQUE (name)
);

COMMENT ON TABLE  action_types             IS 'Справочник видов экологических действий для эко-дневника';
COMMENT ON COLUMN action_types.id          IS 'Идентификатор вида действия';
COMMENT ON COLUMN action_types.name        IS 'Название вида действия';
COMMENT ON COLUMN action_types.unit        IS 'Единица измерения значения (кг, км, л, шт.)';
COMMENT ON COLUMN action_types.description IS 'Пояснение для пользователя';
COMMENT ON COLUMN action_types.is_active   IS 'Признак доступности в форме дневника';

-- ---------------------------------------------------------------------
-- 3. Учебные курсы
-- ---------------------------------------------------------------------
CREATE TABLE courses (
  id         integer GENERATED BY DEFAULT AS IDENTITY,
  title      varchar(200) NOT NULL,
  short_desc varchar(500),
  content    text,
  author_id  integer,
  created_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT courses_pkey PRIMARY KEY (id),
  CONSTRAINT courses_author_fkey FOREIGN KEY (author_id)
    REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX courses_author_idx ON courses (author_id);

COMMENT ON TABLE  courses            IS 'Учебные курсы экологической направленности';
COMMENT ON COLUMN courses.id         IS 'Идентификатор курса';
COMMENT ON COLUMN courses.title      IS 'Название курса';
COMMENT ON COLUMN courses.short_desc IS 'Краткое описание для каталога';
COMMENT ON COLUMN courses.content    IS 'Полное описание (HTML)';
COMMENT ON COLUMN courses.author_id  IS 'Автор курса (преподаватель); NULL — курс без автора';
COMMENT ON COLUMN courses.created_at IS 'Дата создания';

-- ---------------------------------------------------------------------
-- 4. Разделы курсов
-- ---------------------------------------------------------------------
CREATE TABLE course_sections (
  id         integer GENERATED BY DEFAULT AS IDENTITY,
  course_id  integer      NOT NULL,
  title      varchar(200) NOT NULL,
  content    text,
  position   integer      NOT NULL DEFAULT 1,
  created_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT course_sections_pkey PRIMARY KEY (id),
  CONSTRAINT course_sections_course_fkey FOREIGN KEY (course_id)
    REFERENCES courses (id) ON DELETE CASCADE,
  CONSTRAINT course_sections_position_check CHECK (position > 0)
);
CREATE INDEX course_sections_course_idx ON course_sections (course_id, position);

COMMENT ON TABLE  course_sections            IS 'Разделы (темы) учебных курсов';
COMMENT ON COLUMN course_sections.id         IS 'Идентификатор раздела';
COMMENT ON COLUMN course_sections.course_id  IS 'Курс, к которому относится раздел';
COMMENT ON COLUMN course_sections.title      IS 'Заголовок раздела';
COMMENT ON COLUMN course_sections.content    IS 'Содержимое раздела (HTML)';
COMMENT ON COLUMN course_sections.position   IS 'Порядковый номер в курсе';
COMMENT ON COLUMN course_sections.created_at IS 'Дата создания';

-- ---------------------------------------------------------------------
-- 5. Учебные материалы (ссылки, файлы, видео)
-- ---------------------------------------------------------------------
CREATE TABLE materials (
  id            integer GENERATED BY DEFAULT AS IDENTITY,
  course_id     integer,
  section_id    integer,
  title         varchar(200) NOT NULL,
  description   varchar(1000),
  type          varchar(10)  NOT NULL DEFAULT 'link',
  url           varchar(500),
  file_path     varchar(500),
  original_name varchar(255),
  mime_type     varchar(120),
  file_size     bigint,
  uploaded_by   integer,
  created_at    timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT materials_pkey PRIMARY KEY (id),
  CONSTRAINT materials_type_check CHECK (type IN ('link', 'file', 'video')),
  CONSTRAINT materials_course_fkey FOREIGN KEY (course_id)
    REFERENCES courses (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT materials_section_fkey FOREIGN KEY (section_id)
    REFERENCES course_sections (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT materials_uploader_fkey FOREIGN KEY (uploaded_by)
    REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX materials_course_idx  ON materials (course_id);
CREATE INDEX materials_section_idx ON materials (section_id);

COMMENT ON TABLE  materials               IS 'Учебные материалы: ссылки, загруженные файлы, видео';
COMMENT ON COLUMN materials.id            IS 'Идентификатор материала';
COMMENT ON COLUMN materials.course_id     IS 'Курс (может быть пустым для общих материалов библиотеки)';
COMMENT ON COLUMN materials.section_id    IS 'Раздел курса';
COMMENT ON COLUMN materials.title         IS 'Название материала';
COMMENT ON COLUMN materials.description   IS 'Описание';
COMMENT ON COLUMN materials.type          IS 'Тип: link — ссылка, file — файл, video — видео';
COMMENT ON COLUMN materials.url           IS 'Адрес ссылки или видео';
COMMENT ON COLUMN materials.file_path     IS 'Путь к загруженному файлу на сервере';
COMMENT ON COLUMN materials.original_name IS 'Исходное имя загруженного файла';
COMMENT ON COLUMN materials.mime_type     IS 'MIME-тип файла';
COMMENT ON COLUMN materials.file_size     IS 'Размер файла, байт';
COMMENT ON COLUMN materials.uploaded_by   IS 'Пользователь, загрузивший материал';
COMMENT ON COLUMN materials.created_at    IS 'Дата добавления';

-- ---------------------------------------------------------------------
-- 6. Записи студентов на курсы (связь M:N пользователь — курс)
-- ---------------------------------------------------------------------
CREATE TABLE enrollments (
  user_id     integer NOT NULL,
  course_id   integer NOT NULL,
  enrolled_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT enrollments_pkey PRIMARY KEY (user_id, course_id),
  CONSTRAINT enrollments_user_fkey   FOREIGN KEY (user_id)   REFERENCES users (id)   ON DELETE CASCADE,
  CONSTRAINT enrollments_course_fkey FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE
);
CREATE INDEX enrollments_course_idx ON enrollments (course_id);

COMMENT ON TABLE  enrollments             IS 'Записи студентов на курсы';
COMMENT ON COLUMN enrollments.user_id     IS 'Студент';
COMMENT ON COLUMN enrollments.course_id   IS 'Курс';
COMMENT ON COLUMN enrollments.enrolled_at IS 'Дата записи';

-- ---------------------------------------------------------------------
-- 7. Эко-дневник: записи об экологических действиях
-- ---------------------------------------------------------------------
CREATE TABLE eco_entries (
  id         integer GENERATED BY DEFAULT AS IDENTITY,
  user_id    integer       NOT NULL,
  type       varchar(120)  NOT NULL,
  value      numeric(10,2) NOT NULL DEFAULT 0,
  note       varchar(500),
  created_at timestamp(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT eco_entries_pkey PRIMARY KEY (id),
  CONSTRAINT eco_entries_user_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT eco_entries_value_check CHECK (value >= 0)
);
CREATE INDEX eco_entries_user_idx ON eco_entries (user_id, created_at DESC);

COMMENT ON TABLE  eco_entries            IS 'Записи эко-дневника обучающихся';
COMMENT ON COLUMN eco_entries.id         IS 'Идентификатор записи';
COMMENT ON COLUMN eco_entries.user_id    IS 'Автор записи';
COMMENT ON COLUMN eco_entries.type       IS 'Вид экологического действия (название из справочника action_types)';
COMMENT ON COLUMN eco_entries.value      IS 'Количественный показатель в единицах вида действия';
COMMENT ON COLUMN eco_entries.note       IS 'Комментарий пользователя';
COMMENT ON COLUMN eco_entries.created_at IS 'Дата и время записи';

-- ---------------------------------------------------------------------
-- 8. Экологические мероприятия
-- ---------------------------------------------------------------------
CREATE TABLE events (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  title       varchar(200)  NOT NULL,
  description varchar(1000),
  location    varchar(200),
  starts_at   timestamp(0)  NOT NULL,
  seats       integer       NOT NULL DEFAULT 100,
  created_at  timestamp(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT events_pkey PRIMARY KEY (id),
  CONSTRAINT events_seats_check CHECK (seats >= 0)
);
CREATE INDEX events_starts_idx ON events (starts_at);

COMMENT ON TABLE  events             IS 'Экологические мероприятия (акции, лекции, субботники)';
COMMENT ON COLUMN events.id          IS 'Идентификатор мероприятия';
COMMENT ON COLUMN events.title       IS 'Название';
COMMENT ON COLUMN events.description IS 'Описание';
COMMENT ON COLUMN events.location    IS 'Место проведения';
COMMENT ON COLUMN events.starts_at   IS 'Дата и время начала';
COMMENT ON COLUMN events.seats       IS 'Лимит мест';
COMMENT ON COLUMN events.created_at  IS 'Дата публикации';

-- ---------------------------------------------------------------------
-- 9. Регистрации на мероприятия (связь M:N пользователь — мероприятие)
-- ---------------------------------------------------------------------
CREATE TABLE event_registrations (
  user_id       integer NOT NULL,
  event_id      integer NOT NULL,
  registered_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT event_registrations_pkey PRIMARY KEY (user_id, event_id),
  CONSTRAINT event_registrations_user_fkey  FOREIGN KEY (user_id)  REFERENCES users (id)  ON DELETE CASCADE,
  CONSTRAINT event_registrations_event_fkey FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE
);
CREATE INDEX event_registrations_event_idx ON event_registrations (event_id);

COMMENT ON TABLE  event_registrations               IS 'Регистрации обучающихся на мероприятия';
COMMENT ON COLUMN event_registrations.user_id       IS 'Участник';
COMMENT ON COLUMN event_registrations.event_id      IS 'Мероприятие';
COMMENT ON COLUMN event_registrations.registered_at IS 'Дата регистрации';

-- ---------------------------------------------------------------------
-- 10. Справочник бейджей (достижений)
-- ---------------------------------------------------------------------
CREATE TABLE badges (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  code        varchar(64)  NOT NULL,
  name        varchar(200) NOT NULL,
  description varchar(500),
  created_at  timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT badges_pkey PRIMARY KEY (id),
  CONSTRAINT badges_code_key UNIQUE (code)
);

COMMENT ON TABLE  badges             IS 'Справочник бейджей (достижений)';
COMMENT ON COLUMN badges.id          IS 'Идентификатор бейджа';
COMMENT ON COLUMN badges.code        IS 'Код бейджа, используется в правилах начисления';
COMMENT ON COLUMN badges.name        IS 'Название';
COMMENT ON COLUMN badges.description IS 'Условие получения';
COMMENT ON COLUMN badges.created_at  IS 'Дата создания';

-- ---------------------------------------------------------------------
-- 11. Полученные бейджи (связь M:N пользователь — бейдж)
-- ---------------------------------------------------------------------
CREATE TABLE user_badges (
  user_id    integer NOT NULL,
  badge_id   integer NOT NULL,
  awarded_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT user_badges_pkey PRIMARY KEY (user_id, badge_id),
  CONSTRAINT user_badges_user_fkey  FOREIGN KEY (user_id)  REFERENCES users (id)  ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT user_badges_badge_fkey FOREIGN KEY (badge_id) REFERENCES badges (id) ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX user_badges_badge_idx ON user_badges (badge_id);

COMMENT ON TABLE  user_badges            IS 'Факты получения бейджей пользователями';
COMMENT ON COLUMN user_badges.user_id    IS 'Пользователь';
COMMENT ON COLUMN user_badges.badge_id   IS 'Бейдж';
COMMENT ON COLUMN user_badges.awarded_at IS 'Дата начисления';

-- ---------------------------------------------------------------------
-- 12. Обращения через форму обратной связи
-- ---------------------------------------------------------------------
CREATE TABLE feedback (
  id         integer GENERATED BY DEFAULT AS IDENTITY,
  user_id    integer,
  name       varchar(100) NOT NULL,
  email      varchar(190) NOT NULL,
  message    text         NOT NULL,
  status     varchar(16)  NOT NULL DEFAULT 'new',
  created_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT feedback_pkey PRIMARY KEY (id),
  CONSTRAINT feedback_user_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT feedback_status_check CHECK (status IN ('new', 'in_progress', 'closed'))
);
CREATE INDEX feedback_status_idx ON feedback (status, created_at DESC);

COMMENT ON TABLE  feedback            IS 'Обращения пользователей через форму обратной связи';
COMMENT ON COLUMN feedback.id         IS 'Идентификатор обращения';
COMMENT ON COLUMN feedback.user_id    IS 'Пользователь (NULL — обращение гостя)';
COMMENT ON COLUMN feedback.name       IS 'Имя отправителя';
COMMENT ON COLUMN feedback.email      IS 'E-mail для ответа';
COMMENT ON COLUMN feedback.message    IS 'Текст обращения';
COMMENT ON COLUMN feedback.status     IS 'Статус: new — новое, in_progress — в работе, closed — закрыто';
COMMENT ON COLUMN feedback.created_at IS 'Дата обращения';

